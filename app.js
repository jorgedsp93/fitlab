function workoutExportDetail(week,dayIndex){
  const plan=planFor(week,dayIndex);
  const dk=dayKey(week,dayIndex);
  const workoutDate=dateForPos(week,dayIndex);
  const exercises=[];
  let doneSets=0;
  let heaviest=null;

  for(const planned of loggedExercises(plan,dk)){
    const exercise=EXERCISES[planned.id];
    if(!exercise) continue;
    const logged=((S.logs[dk]||{})[planned.id]||[])
      .map((set,index)=>({
        set:index+1,
        weight:set.w===''||set.w==null?null:Number(set.w),
        totalWeight:set.w===''||set.w==null?null:totalLoadForExercise(planned.id,set.w),
        weightLabel:loadMeta(planned.id).label,
        reps:set.r===''||set.r==null?null:Number(set.r),
        done:set.done===true,
      }))
      .filter(set=>set.done);
    if(!logged.length) continue;
    doneSets+=logged.length;
    for(const set of logged){
      const weight=Number(set.totalWeight||set.weight||0);
      if(weight>0 && (!heaviest || weight>heaviest.totalWeight)){
        heaviest={ exercise:exercise.name, weight:set.weight, totalWeight:weight, weightLabel:set.weightLabel, reps:set.reps };
      }
    }
    exercises.push({
      id:planned.id,
      name:exercise.name,
      targetReps:planned.reps,
      plannedSets:planned.plannedSets,
      restSeconds:planned.rest||60,
      primary:exercise.primary||[],
      secondary:exercise.secondary||[],
      equipment:exercise.equipment||'',
      garmin:garminExerciseFor(planned.id),
      sets:logged,
    });
  }

  const durationSeconds=estimateWorkoutSeconds(exercises);
  let start=new Date(workoutDate.getFullYear(),workoutDate.getMonth(),workoutDate.getDate(),18,0,0);
  const now=new Date();
  if(ymd(workoutDate)===todayISO()&&start>now) start=new Date(Math.max(new Date(todayISO()+'T00:00').getTime(),now.getTime()-durationSeconds*1000));
  const end=new Date(start.getTime()+durationSeconds*1000);
  const calories=Math.max(25,Math.round(durationSeconds/60*6));

  return {
    source:'FitLab',
    exportVersion:1,
    exportedAt:new Date().toISOString(),
    workout:{
      key:dk,
      week,
      dayIndex,
      dayNumber:dayIndex+1,
      title:plan.title,
      date:ymd(workoutDate),
      phase:PHASES[plan.phase].name,
      unit:S.unit,
      rideLogged:rideOn(week,dayIndex),
      cardioNote:plan.cardio?.d||'',
    },
    timing:{
      estimated:true,
      startTime:start.toISOString(),
      endTime:end.toISOString(),
      durationSeconds,
    },
    summary:{
      doneExercises:exercises.length,
      doneSets,
      durationSeconds,
      calories,
      heaviest,
    },
    exercises,
  };
}

function estimateWorkoutSeconds(exercises){
  let seconds=0;
  const all=exercises.flatMap(exercise=>exercise.sets.map(set=>({exercise,set})));
  all.forEach(({exercise,set},i)=>{seconds+=activeSetSeconds(set);if(i<all.length-1)seconds+=exercise.restSeconds||60;});
  return Math.max(1,Math.round(seconds));
}
function activeSetSeconds(set){const reps=Number(set.reps);return Math.max(20,Math.min(90,(Number.isFinite(reps)&&reps>0?reps:8)*4+12));}

