function fitTimestamp(date){
  return Math.max(0,Math.round((new Date(date).getTime()-FIT_EPOCH_MS)/1000));
}

function fitLocalTimestamp(date){
  const d=new Date(date);
  return Math.max(0,Math.round((d.getTime()-FIT_EPOCH_MS-(d.getTimezoneOffset()*60000))/1000));
}

function fitCrc(bytes,start=0,end=bytes.length){
  let crc=0;
  for(let i=start;i<end;i++){
    let tmp=FIT_CRC_TABLE[crc & 0xf];
    crc=(crc>>4)&0x0fff;
    crc=crc ^ tmp ^ FIT_CRC_TABLE[bytes[i] & 0xf];
    tmp=FIT_CRC_TABLE[crc & 0xf];
    crc=(crc>>4)&0x0fff;
    crc=crc ^ tmp ^ FIT_CRC_TABLE[(bytes[i]>>4)&0xf];
  }
  return crc & 0xffff;
}

class FitWriter{
  constructor(){ this.bytes=[]; }
  u8(v){ this.bytes.push((v??0)&0xff); }
  u16(v){ this.u8(v); this.u8((v??0)>>8); }
  u32(v){ v=Number(v??0)>>>0; this.u8(v); this.u8(v>>8); this.u8(v>>16); this.u8(v>>24); }
  str(value,size){
    const encoded=new TextEncoder().encode(String(value??''));
    const limit=Math.max(0,size-1);
    for(let i=0;i<size;i++) this.u8(i<Math.min(encoded.length,limit)?encoded[i]:0);
  }
  writeValue(field,value){
    if(field.type===FIT_TYPES.STRING){ this.str(value,field.size); return; }
    const invalid=FIT_INVALID[field.type] ?? 0xff;
    const v=value!=null&&Number.isFinite(Number(value)) ? Number(value) : invalid;
    if(field.type===FIT_TYPES.UINT16) this.u16(v);
    else if(field.type===FIT_TYPES.UINT32 || field.type===FIT_TYPES.UINT32Z) this.u32(v);
    else this.u8(v);
  }
  definition(localNum,globalNum,fields){
    this.u8(0x40 | localNum);
    this.u8(0);
    this.u8(0);
    this.u16(globalNum);
    this.u8(fields.length);
    fields.forEach(f=>{ this.u8(f.num); this.u8(f.size); this.u8(f.type); });
  }
  message(localNum,fields,values){
    this.u8(localNum);
    fields.forEach(f=>this.writeValue(f,values[f.key]));
  }
  close(){
    const data=new Uint8Array(this.bytes);
    const header=new Uint8Array(14);
    const hv=new DataView(header.buffer);
    header[0]=14;
    header[1]=0x20;
    hv.setUint16(2,FIT_PROFILE_VERSION,true);
    hv.setUint32(4,data.length,true);
    header[8]=0x2e; header[9]=0x46; header[10]=0x49; header[11]=0x54;
    hv.setUint16(12,fitCrc(header,0,12),true);
    const withoutCrc=new Uint8Array(header.length+data.length);
    withoutCrc.set(header,0);
    withoutCrc.set(data,header.length);
    const out=new Uint8Array(withoutCrc.length+2);
    out.set(withoutCrc,0);
    new DataView(out.buffer).setUint16(out.length-2,fitCrc(withoutCrc),true);
    return out;
  }
}

function fitWeightRaw(weight,unit){
  const n=Number(weight);
  if(!Number.isFinite(n) || n<=0) return null;
  const kg=unit==='kg' ? n : n/2.2046226218;
  return Math.max(0,Math.min(0xfffe,Math.round(kg*16)));
}

function fitWorkoutSets(detail){
  const rows=[];
  let cursor=new Date(detail.timing.startTime).getTime();
  for(const exercise of detail.exercises){
    for(const set of exercise.sets){
      const reps=Number(set.reps);
      const activeSeconds=activeSetSeconds(set);
      const start=new Date(cursor);
      const end=new Date(cursor+activeSeconds*1000);
      rows.push({exercise,set,start,end,durationSeconds:activeSeconds});
      cursor=end.getTime()+(exercise.restSeconds||60)*1000;
    }
  }
  return rows;
}

